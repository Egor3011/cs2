def dot_background(c, doc):
    c.saveState()
    page_no = c.getPageNumber()
    c.setFillColor(PALE_BLUE)
    step = 7.2
    radius = 0.42
    x0, x1 = 12 * mm, W - 12 * mm
    y0, y1 = 10 * mm, H - 10 * mm
    row = 0
    y = y0
    while y <= y1:
        offset = (step / 2) if row % 2 else 0
        x = x0 + offset
        while x <= x1:
            c.circle(x, y, radius, stroke=0, fill=1)
            x += step
        y += step
        row += 1

    # Large halftone privacy shield, deliberately quiet behind the text.
    rng = random.Random(5400 + page_no)
    cx = W * (0.66 if page_no % 2 else 0.38)
    cy = H * (0.52 if page_no > 1 else 0.48)
    scale = 1.0 if page_no > 1 else 1.25
    spacing = 7.0
    c.setFillColor(HexColor("#A8DBFA"))
    yy = -150 * scale
    while yy <= 165 * scale:
        xx = -118 * scale
        while xx <= 118 * scale:
            # Shield mask: wide top, tapering lower half.
            yn = yy / scale
            xn = xx / scale
            width = 106 if yn > -5 else max(12, 106 - (-yn - 5) * 0.63)
            inside = abs(xn) <= width and -145 <= yn <= 145
            notch = yn > 104 and abs(xn) > (85 - (yn - 104) * 0.55)
            if inside and not notch and rng.random() > 0.12:
                rr = (1.45 if page_no == 1 else 1.15) * scale
                c.circle(cx + xx, cy + yy, rr, stroke=0, fill=1)
            xx += spacing * scale
        yy += spacing * scale

    # Keyhole motif inside the shield.
    c.setFillColor(HexColor("#87CCF7"))
    c.circle(cx, cy + 22 * scale, 22 * scale, stroke=0, fill=1)
    p = c.beginPath()
    p.moveTo(cx - 12 * scale, cy + 8 * scale)
    p.lineTo(cx + 12 * scale, cy + 8 * scale)
    p.lineTo(cx + 24 * scale, cy - 72 * scale)
    p.lineTo(cx - 24 * scale, cy - 72 * scale)
    p.close()
    c.drawPath(p, stroke=0, fill=1)

    # White wash keeps long-form text crisp while retaining the sample's texture.
    c.setFillColor(colors.Color(1, 1, 1, alpha=0.72))
    c.rect(13 * mm, 14 * mm, W - 26 * mm, H - 28 * mm, stroke=0, fill=1)

    if page_no > 1:
        c.setFont("Arial-Bold", 7.3)
        c.setFillColor(MID)
        c.drawString(17 * mm, H - 12 * mm, "[НАИМЕНОВАНИЕ ОПЕРАТОРА]  /  ПЕРСОНАЛЬНЫЕ ДАННЫЕ")
        c.setStrokeColor(RULE)
        c.setLineWidth(0.45)
        c.line(17 * mm, H - 15 * mm, W - 17 * mm, H - 15 * mm)

        c.setFont("Arial-Bold", 7.2)
        c.setFillColor(MAGENTA)
        c.drawString(17 * mm, 10.5 * mm, "PD / REGULATION")
        c.setFont("Arial", 7.2)
        c.setFillColor(MID)
        c.drawRightString(W - 17 * mm, 10.5 * mm, f"{page_no:02d}")
    c.restoreState()


def qr_drawing(value: str, size: float = 31 * mm) -> Drawing:
    widget = qr.QrCodeWidget(value)
    x1, y1, x2, y2 = widget.getBounds()
    w, h = x2 - x1, y2 - y1
    drawing = Drawing(size, size, transform=[size / w, 0, 0, size / h, 0, 0])
    drawing.add(widget)
    return drawing


