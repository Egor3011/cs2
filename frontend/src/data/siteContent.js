export function siteContent(data) {
  return { ...structuredClone(defaultSiteContent), ...Object.fromEntries(Object.entries(data ?? {}).filter(([, value]) => value != null)) }
}

export function safeExternalUrl(value) {
  try { const url = new URL(value); return ['https:', 'http:'].includes(url.protocol) ? url.href : '' } catch { return '' }
}
